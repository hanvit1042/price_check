const sig = (d) => (d ? Math.max(-20, Math.min(20, -d.chg)) : 0); // 싸질수록 +

/** 오늘의 추천 메뉴. dealMap: Map(name → deal), have: 시세 있는 품목 이름 Set. 같은 날은 같은 순서(날짜로 동점 처리) */
export function suggestRecipes(dealMap, have, month, seed = 0) {
  const out = [];
  for (const r of RECIPES) {
    const mains = r.main.filter((n) => have.has(n));
    if (mains.length < Math.min(2, r.main.length) || !have.has(r.main[0])) continue;
    const star = dealMap.get(r.main[0]);
    if (star && star.chg >= 5) continue; // 주인공 재료가 오르는 중이면 제외
    const rest = mains.slice(1).map((n) => sig(dealMap.get(n)));
    const score = sig(star) * 2 + (rest.length ? rest.reduce((a, b) => a + b, 0) / rest.length : 0)
      + mains.filter((n) => inSeason(n, month)).length * 3 + ((seed + r.n.length) % 5) * 0.1;
    const best = mains.map((n) => dealMap.get(n)).filter((d) => d && d.chg <= -3).sort((a, b) => a.chg - b.chg)[0];
    const seasonal = mains.find((n) => inSeason(n, month));
    const reason = best ? { type: 'down', name: best.name, pct: Math.abs(best.chg), since: best.since } : seasonal ? { type: 'season', name: seasonal } : { type: 'stable' };
    out.push({ ...r, mains, score, reason });
  }
  return out.filter((r) => r.score > 0 || r.reason.type !== 'stable').sort((a, b) => b.score - a.score);
}
